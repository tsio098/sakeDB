// Score one sake against a mood def
function scoreFor(sake, mood) {
  if (!mood) return 0;
  let score = 0;
  for (const t of sake.tags) {
    if (mood.core.includes(t)) score += 2;
    else if (mood.sub.includes(t)) score += 1;
  }
  return score;
}

